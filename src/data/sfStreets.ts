// Deduplicate and alphabetize
export const UNIQUE_SF_STREETS = Array.from(new Set(SF_STREETS)).sort((a, b) => {
  // Sort numbers naturally if both start with digits
  const numA = parseInt(a, 10);
  const numB = parseInt(b, 10);
  if (!isNaN(numA) && !isNaN(numB)) {
    return numA - numB;
  }
  return a.localeCompare(b);
});

/**
 * Filter SF streets based on search query with smart ranking:
 * 1. Exact startsWith match
 * 2. Word startsWith match (e.g. "Market" matches "South Market St")
 * 3. Includes match
 */
export function searchSFStreets(query: string, limit = 25): string[] {
  const clean = query.trim().toLowerCase();
  if (!clean) {
    return POPULAR_SF_STREETS.slice(0, limit);
  }

  const startsWithExact: string[] = [];
  const startsWithWord: string[] = [];
  const contains: string[] = [];

  for (const street of UNIQUE_SF_STREETS) {
    const lower = street.toLowerCase();
    if (lower === clean) {
      startsWithExact.unshift(street);
    } else if (lower.startsWith(clean)) {
      startsWithExact.push(street);
    } else if (lower.split(' ').some((word) => word.startsWith(clean))) {
      startsWithWord.push(street);
    } else if (lower.includes(clean)) {
      contains.push(street);
    }

    if (startsWithExact.length >= limit) break;
  }

  const results = [...startsWithExact, ...startsWithWord, ...contains];
  return Array.from(new Set(results)).slice(0, limit);
}

